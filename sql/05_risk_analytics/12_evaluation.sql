-- BANKGUARD AI – M2 Ground-Truth Scenario Evaluation
-- Compares detected signals against SCENARIO_METADATA ground truth.

USE DATABASE BANKGUARD_DB;
USE SCHEMA BANKGUARD_RISK;

CREATE OR REPLACE VIEW V_RISK_SCENARIO_EVALUATION AS
WITH type_map AS (
    SELECT column1 AS scenario_type, column2 AS signal_type FROM VALUES
    ('VELOCITY_SPIKE','VELOCITY'),('STRUCTURING','STRUCTURING'),
    ('BENEFICIARY_BURST','BENEFICIARY_BURST'),('GEO_ANOMALY','GEO_ANOMALY'),
    ('DORMANT_ACTIVATION','DORMANT_ACTIVATION'),('VALUE_SPIKE','VALUE_SPIKE'),
    ('CHANNEL_ANOMALY','CHANNEL_ANOMALY'),('NETWORK_PATTERN','NETWORK_PATTERN'),
    ('COMBINED','MULTI_SIGNAL')
),
scenario_custs AS (
    SELECT sm.SCENARIO_ID, sm.SCENARIO_TYPE, sm.CUSTOMER_ID AS lead_customer,
           sm.EXPECTED_RISK_CLASS, tm.signal_type AS expected_signal, c.CUSTOMER_ID
    FROM BANKGUARD_RAW.SCENARIO_METADATA sm
    JOIN type_map tm ON sm.SCENARIO_TYPE = tm.scenario_type
    JOIN BANKGUARD_RAW.CUSTOMERS c
        ON c.CUSTOMER_ID >= sm.CUSTOMER_ID
        AND c.CUSTOMER_ID <= CASE WHEN sm.SCENARIO_TYPE = 'COMBINED' THEN sm.CUSTOMER_ID
            ELSE SUBSTRING(sm.CUSTOMER_ID, 1, 7) ||
                 LPAD((SUBSTRING(sm.CUSTOMER_ID, 8)::INT + 4)::VARCHAR, 2, '0') END
),
per_cust AS (
    SELECT sc.SCENARIO_ID, sc.SCENARIO_TYPE, sc.CUSTOMER_ID, sc.lead_customer,
           sc.EXPECTED_RISK_CLASS, e.SIGNAL_TYPE AS detected_signal,
           rs.RISK_SCORE, rs.RISK_CLASS
    FROM scenario_custs sc
    LEFT JOIN RISK_SIGNAL_EVIDENCE e ON sc.CUSTOMER_ID = e.CUSTOMER_ID AND e.SIGNAL_TYPE = sc.expected_signal
    LEFT JOIN CUSTOMER_RISK_SCORE rs ON sc.CUSTOMER_ID = rs.CUSTOMER_ID
)
SELECT SCENARIO_ID, SCENARIO_TYPE, lead_customer, EXPECTED_RISK_CLASS,
       COUNT(DISTINCT CUSTOMER_ID) AS CUSTOMER_COUNT,
       COUNT(DISTINCT CASE WHEN detected_signal IS NOT NULL THEN CUSTOMER_ID END) AS DETECTED_COUNT,
       COUNT(DISTINCT CASE WHEN detected_signal IS NULL THEN CUSTOMER_ID END) AS FALSE_NEGATIVE_COUNT,
       ROUND(COUNT(DISTINCT CASE WHEN detected_signal IS NOT NULL THEN CUSTOMER_ID END) * 100.0 /
             NULLIF(COUNT(DISTINCT CUSTOMER_ID), 0), 0) AS DETECTION_RATE_PCT
FROM per_cust
GROUP BY SCENARIO_ID, SCENARIO_TYPE, lead_customer, EXPECTED_RISK_CLASS;
